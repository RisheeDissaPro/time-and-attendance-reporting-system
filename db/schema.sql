-- =====================================================================
-- SecureLock Global - Time and Attendance Reporting System
-- Database schema (PostgreSQL 16)
--
-- Layers:
--   staging.raw_attendance   raw CSV rows exactly as exported (all TEXT)
--   public.*                 reference data, cleaned attendance, derived exceptions
-- =====================================================================

BEGIN;

CREATE SCHEMA IF NOT EXISTS staging;

-- ---------------------------------------------------------------------
-- Raw layer
-- ---------------------------------------------------------------------
CREATE TABLE staging.raw_attendance (
    raw_id         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    source_file    TEXT        NOT NULL,
    file_checksum  CHAR(64)    NOT NULL,
    row_number     INTEGER     NOT NULL,
    employee_id    TEXT,
    date           TEXT,
    clock_in       TEXT,
    clock_out      TEXT,
    loaded_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (file_checksum, row_number)
);

-- ---------------------------------------------------------------------
-- Reference data
-- ---------------------------------------------------------------------
CREATE TABLE departments (
    department_id  INTEGER PRIMARY KEY,
    name           TEXT NOT NULL UNIQUE,
    business_unit  TEXT NOT NULL
);

CREATE TABLE employees (
    employee_id    INTEGER PRIMARY KEY,
    name           TEXT    NOT NULL,
    department_id  INTEGER NOT NULL REFERENCES departments (department_id),
    role           TEXT    NOT NULL,
    manager_id     INTEGER REFERENCES employees (employee_id),
    CHECK (manager_id IS NULL OR manager_id <> employee_id)
);

CREATE TABLE rosters (
    roster_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id      INTEGER   NOT NULL REFERENCES employees (employee_id),
    scheduled_start  TIMESTAMP NOT NULL,
    scheduled_end    TIMESTAMP NOT NULL,
    shift_date       DATE      NOT NULL,
    UNIQUE (employee_id, shift_date),
    CHECK (scheduled_end > scheduled_start)
);

-- ---------------------------------------------------------------------
-- Cleaned attendance
-- ---------------------------------------------------------------------
CREATE TABLE attendance_records (
    record_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id   INTEGER      NOT NULL REFERENCES employees (employee_id),
    clock_in      TIMESTAMP    NOT NULL,
    clock_out     TIMESTAMP,
    date          DATE         NOT NULL,
    hours_worked  NUMERIC(5, 2),
    loaded_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    UNIQUE (employee_id, date),
    CHECK (clock_out IS NULL OR clock_out > clock_in),
    CHECK (hours_worked IS NULL OR hours_worked >= 0)
);

-- ---------------------------------------------------------------------
-- Derived exceptions
-- ---------------------------------------------------------------------
CREATE TABLE exceptions (
    exception_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id   INTEGER     NOT NULL REFERENCES employees (employee_id),
    record_id     BIGINT      NOT NULL REFERENCES attendance_records (record_id)
                                  ON DELETE CASCADE,
    type          TEXT        NOT NULL
                      CHECK (type IN ('missed_clock_in', 'overtime', 'roster_breach')),
    date          DATE        NOT NULL,
    status        TEXT        NOT NULL DEFAULT 'open'
                      CHECK (status IN ('open', 'resolved', 'escalated')),
    details       TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (record_id, type)
);

CREATE FUNCTION set_updated_at() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

CREATE TRIGGER exceptions_set_updated_at
    BEFORE UPDATE ON exceptions
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------
-- Indexes: foreign keys and date columns
-- ---------------------------------------------------------------------
CREATE INDEX idx_raw_attendance_checksum      ON staging.raw_attendance (file_checksum);

CREATE INDEX idx_employees_department_id      ON employees (department_id);
CREATE INDEX idx_employees_manager_id         ON employees (manager_id);

CREATE INDEX idx_rosters_employee_id          ON rosters (employee_id);
CREATE INDEX idx_rosters_shift_date           ON rosters (shift_date);

CREATE INDEX idx_attendance_employee_id       ON attendance_records (employee_id);
CREATE INDEX idx_attendance_date              ON attendance_records (date);

CREATE INDEX idx_exceptions_employee_id       ON exceptions (employee_id);
CREATE INDEX idx_exceptions_record_id         ON exceptions (record_id);
CREATE INDEX idx_exceptions_date              ON exceptions (date);
CREATE INDEX idx_exceptions_status            ON exceptions (status);

COMMIT;
